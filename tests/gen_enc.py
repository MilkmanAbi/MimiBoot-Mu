#!/usr/bin/env python3
"""
Writes tests/gen_enc.h: key envelopes and encrypted bodies for the C tests.

Two independent sources, so the device code is checked against something it
didn't write:
  - imgtool (MCUboot's own tool, pyca/cryptography underneath) encrypting an
    image for a test X25519 key, AES-128 and AES-256: the 0x33 TLV and body
    are cut out of its output;
  - tools/mb_enc.py (what mbtool uses), checked here against pyca first.

Needs `pip install imgtool` (which brings cryptography); run it by hand when
the format changes:  python tests/gen_enc.py > tests/gen_enc.h
Set IMGTOOL to the imgtool executable if it isn't on PATH.
"""
import hashlib
import os
import shutil
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import mb_enc  # noqa: E402

from cryptography.hazmat.primitives import serialization  # noqa: E402
from cryptography.hazmat.primitives.asymmetric.x25519 import X25519PrivateKey  # noqa: E402

PRIV = hashlib.sha256(b"MimiBoot test encryption key").digest()
OTHER = hashlib.sha256(b"some other device").digest()


def c_bytes(b: bytes) -> str:
    return "{" + ",".join(f"0x{x:02x}" for x in b) + "}"


def imgtool_vector(tmp: Path, keylen: int, body: bytes):
    pub = X25519PrivateKey.from_private_bytes(PRIV).public_key()
    pem = tmp / "enc_pub.pem"
    pem.write_bytes(pub.public_bytes(serialization.Encoding.PEM, serialization.PublicFormat.SubjectPublicKeyInfo))
    src, out = tmp / "in.bin", tmp / f"out{keylen}.bin"
    src.write_bytes(body)
    imgtool = os.environ.get("IMGTOOL") or shutil.which("imgtool") or "imgtool"
    args = [imgtool, "sign", "--header-size", "0x200", "--pad-header", "--align", "4", "--version", "1.2.3",
            "--slot-size", "0x20000", "--encrypt", str(pem)]
    if keylen == 256:
        args += ["--encrypt-keylen", "256"]
    subprocess.run(args + [str(src), str(out)], check=True, capture_output=True)
    img = out.read_bytes()
    magic, _, hdr_size, prot, img_size, flags = struct.unpack_from("<IIHHII", img)
    assert magic == 0x96F3B83D and flags & (0x04 | 0x08), "imgtool didn't mark the image encrypted"
    cipher = img[hdr_size:hdr_size + img_size]
    at = hdr_size + img_size + prot
    tlv_magic, tlv_len = struct.unpack_from("<HH", img, at)
    assert tlv_magic == 0x6907
    end, at, env = at + tlv_len, at + 4, None
    while at < end:
        t, _, n = struct.unpack_from("<BBH", img, at)
        if t == mb_enc.TLV_X25519:
            env = img[at:at + 4 + n]
        at += 4 + n
    assert env, "no ENCX25519 TLV"
    # the generator's own decryption has to agree with imgtool before the C test uses it
    key = mb_enc.unwrap(PRIV, env)
    assert len(key) * 8 == keylen and mb_enc.aes_ctr(key, cipher) == body
    return env, cipher


def main():
    # mb_enc.py against pyca before anything is generated with it
    from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes
    for kl in (16, 32):
        k, n, d = os.urandom(kl), os.urandom(16), os.urandom(77)
        e = Cipher(algorithms.AES(k), modes.CTR(n)).encryptor()
        assert mb_enc.aes_ctr(k, d, n) == e.update(d) + e.finalize()
    for _ in range(4):
        a, b = os.urandom(32), os.urandom(32)
        pa = X25519PrivateKey.from_private_bytes(a)
        assert mb_enc.public_key(a) == pa.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)
        assert mb_enc.x25519(a, mb_enc.public_key(b)) == pa.exchange(X25519PrivateKey.from_private_bytes(b).public_key())

    body = bytes((i * 7 + 3) & 0xFF for i in range(1000)) + b"MimiBoot"   # not a multiple of 16
    vecs = []
    with tempfile.TemporaryDirectory() as t:
        for kl in (128, 256):
            env, cipher = imgtool_vector(Path(t), kl, body)
            vecs.append((f"imgtool AES-{kl}", env, cipher))
    for kl in (16, 32):
        key = os.urandom(kl)
        env = mb_enc.wrap(mb_enc.public_key(PRIV), key)
        vecs.append((f"mb_enc.py AES-{kl * 8}", env, mb_enc.aes_ctr(key, body)))

    print("/* generated by tests/gen_enc.py: do not edit */")
    print("#include <stddef.h>\n#include <stdint.h>")
    print(f"static const uint8_t enc_priv[32] = {c_bytes(PRIV)};")
    print(f"static const uint8_t enc_other_priv[32] = {c_bytes(OTHER)};")
    print(f"static const uint8_t enc_pub[32] = {c_bytes(mb_enc.public_key(PRIV))};")
    print(f"#define ENC_BODY_MAX {len(body)}")
    print("typedef struct { const char* name; const uint8_t* env; size_t env_len; const uint8_t* body; size_t body_len; uint8_t plain_sha[32]; } enc_vec_t;")
    for i, (_, env, cipher) in enumerate(vecs):
        print(f"static const uint8_t enc_env{i}[] = {c_bytes(env)};")
        print(f"static const uint8_t enc_body{i}[] = {c_bytes(cipher)};")
    print("static const enc_vec_t enc_vec[] = {")
    for i, (name, env, cipher) in enumerate(vecs):
        print(f'    {{ "{name}", enc_env{i}, {len(env)}, enc_body{i}, {len(cipher)}, {c_bytes(hashlib.sha256(body).digest())} }},')
    print("};")


if __name__ == "__main__":
    main()
