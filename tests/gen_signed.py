# An MCUboot image as tests/test_profile.c's put_mcuboot() builds it (header
# 0x200, v1.2.3, 1024-byte body), signed the way imgtool's ECDSA P-256 does:
# over the image's SHA-256 digest, DER-encoded, in an ECDSA_SIG TLV.
def der_int(v):
    b = v.to_bytes(32, "big").lstrip(b"\0") or b"\0"
    if b[0] & 0x80:
        b = b"\0" + b
    return b"\x02" + bytes([len(b)]) + b


def mcuboot_digest(seed):
    import hashlib
    import struct
    img = bytearray(0x200 + 1024)
    struct.pack_into("<I", img, 0, 0x96f3b83d)
    struct.pack_into("<H", img, 8, 0x200)
    struct.pack_into("<I", img, 12, 1024)
    img[20:23] = b"\x01\x02\x03"
    img[0x200:] = payload(seed, 1024)
    return hashlib.sha256(bytes(img)).digest()


