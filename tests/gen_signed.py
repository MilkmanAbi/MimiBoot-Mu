def payload(seed, size):
    """Same generator as make_payload() in test_mimiboot.c (xorshift32)."""
    x = (seed * 2654435761 + 1) & 0xFFFFFFFF
    out = bytearray(size)
    for i in range(size):
        x ^= (x << 13) & 0xFFFFFFFF
        x ^= x >> 17
        x ^= (x << 5) & 0xFFFFFFFF
        out[i] = x & 0xFF
    return bytes(out)


def c_array(name, data):
    rows = ", ".join("0x%02x" % b for b in data)
    return "__attribute__((unused)) static const uint8_t %s[%d] = { %s };\n" % (name, len(data), rows)


