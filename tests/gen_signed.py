"""
Make signed image headers for the C tests with the same code mbtool uses,
so the tests check Python signing against C verification.

    python tests/gen_signed.py > tests/gen_signed.h
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tools"))
import mb_ed25519 as ed  # noqa: E402
import mbtool  # noqa: E402

RFC1_SECRET = bytes.fromhex("9d61b19deffd5a60ba844af492ec2cc44449c5697b326919703bac031cae7f60")
OTHER_SECRET = bytes(range(1, 33))


def payload(seed, size):
    """Same generator as make_payload() in test_mimiboot.c (xorshift32)."""
    x = (seed * 2654435761 + 1) & 0xFFFFFFFF
    out = bytearray(size)
    for i in range(size):
        x ^= (x << 13) & 0xFFFFFFFF
        x ^= x >> 17
        x ^= (x << 5) & 0xFFFFFFFF
        out[i] = x & 0xFF
    return bytes(out)


def c_array(name, data):
    rows = ", ".join("0x%02x" % b for b in data)
    return "static const uint8_t %s[%d] = { %s };\n" % (name, len(data), rows)


cases = [
    ("signed_good", 11, 40000, RFC1_SECRET, mbtool.parse_version("2.0.0"), 1),
    ("signed_other_key", 12, 40000, OTHER_SECRET, mbtool.parse_version("2.0.1"), 1),
]
print("/* generated by tests/gen_signed.py - do not edit */")
for name, seed, size, secret, version, secver in cases:
    hdr = mbtool.build_header(payload(seed, size), name, version, secver, target="sim", arch=mbtool.ARCH_ARM,
                              secret=secret, build_time=0)
    assert ed.verify(ed.public_key(secret), hdr[:mbtool.SIGNED_BYTES], hdr[mbtool.SIGNED_BYTES:mbtool.SIGNED_BYTES + 64])
    print("#define %s_SEED %d\n#define %s_SIZE %d" % (name.upper(), seed, name.upper(), size))
    print(c_array(name + "_hdr", hdr))
