#!/usr/bin/env python3
"""Turn Wycheproof test vectors into C tables for tests/test_crypto.c.

    python tests/gen_wycheproof.py ed25519 path/to/ed25519_test.json > tests/wycheproof_ed25519.h
    python tests/gen_wycheproof.py p256 path/to/ecdsa_secp256r1_sha256_p1363_test.json > tests/wycheproof_p256.h

Source: https://github.com/C2SP/wycheproof (testvectors_v1), Apache License 2.0.
The generated headers are checked in, so the tests don't need the network.
"""
import json
import sys


def c_bytes(h: str) -> str:
    return '"' + "".join(f"\\x{h[i:i + 2]}" for i in range(0, len(h), 2)) + '"'


def main():
    kind, path = sys.argv[1], sys.argv[2]
    d = json.load(open(path, encoding="utf-8"))
    rows = []
    for g in d["testGroups"]:
        if kind == "ed25519":
            pub = g["publicKey"]["pk"]
        else:                                   # P-256: the raw point X || Y, without the 04 prefix
            unc = g["publicKey"]["uncompressed"]
            assert unc.startswith("04") and len(unc) == 130
            pub = unc[2:]
        for t in g["tests"]:
            res = {"valid": 1, "invalid": 0, "acceptable": 2}[t["result"]]
            sig = t["sig"]
            rows.append(f'  {{{t["tcId"]}, {res}, {c_bytes(pub)}, {c_bytes(t["msg"])}, {len(t["msg"]) // 2}, '
                        f'{c_bytes(sig)}, {len(sig) // 2}}},')
    name = "wp_ed25519" if kind == "ed25519" else "wp_p256"
    src = path.replace("\\", "/").split("/")[-1]
    print(f"/* generated by tests/gen_wycheproof.py from Wycheproof's {src}")
    print(f" * ({d.get('numberOfTests')} tests; https://github.com/C2SP/wycheproof, Apache License 2.0) */")
    print("#ifndef WP_VECTOR_T\n#define WP_VECTOR_T")
    print("typedef struct { int id, result; const char* pub; const char* msg; unsigned msg_len;")
    print("                 const char* sig; unsigned sig_len; } wp_vector_t;   /* result: 1 valid, 0 invalid, 2 acceptable */")
    print("#endif")
    print(f"static const wp_vector_t {name}[] = {{")
    print("\n".join(rows))
    print("};")


if __name__ == "__main__":
    main()
